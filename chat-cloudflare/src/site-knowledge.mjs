function normalized(value) {
  return String(value || "").normalize("NFKC").toLocaleLowerCase("zh-CN");
}

function scoreDocument(document, question) {
  const text = normalized(question);
  if (!text) return 0;
  let score = 0;
  for (const keyword of document.keywords) {
    const key = normalized(keyword);
    if (key && text.includes(key)) score += Math.min(6, Math.max(2, key.length));
  }
  if (/机器人|实验室|学生|课程|项目|任务|助教|保密|协议|入门|学习|理论/u.test(text)) {
    const body = normalized(document.body);
    for (const term of text.match(/[\p{Script=Han}A-Za-z0-9_-]{2,}/gu) || []) {
      if (body.includes(normalized(term))) score += 1;
    }
  }
  return score;
}

export function siteKnowledgeDocuments(question, limit = 3) {
  return SITE_DOCUMENTS
    .map((document) => ({ document, score: scoreDocument(document, question) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ document }) => ({
      id: document.id,
      title: document.title,
      body: document.body,
      url: document.url,
      category: "站内公开资料",
      updatedAt: "2026-09-23",
      published: 1,
      sectionTitle: "",
      paragraphRef: "",
      sourceLabel: "chat.omindos.ai",
      origin: "site_public",
    }));
}
